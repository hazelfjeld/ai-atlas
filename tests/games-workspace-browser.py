"""Exercise the real Atlas Games hash route, shared shell, and route teardown."""
import argparse
import json
import os
from pathlib import Path
from playwright.sync_api import sync_playwright
parser = argparse.ArgumentParser()
parser.add_argument('--base', default='http://127.0.0.1:8765/')
parser.add_argument('--output', default='games-workspace-validation')
a = parser.parse_args()
base = a.base.rstrip('/') + '/'
out = Path(a.output)
out.mkdir(parents=True, exist_ok=True)
checks, errors, requests = [], [], []
def check(label, ok):
    if not ok:
        raise AssertionError(label)
    checks.append(label)
    print('PASS', label, flush=True)
def exit_round(page):
    page.locator('[data-action=menu]').first.click()
with sync_playwright() as p:
    browser = p.chromium.launch(executable_path=os.environ.get('CHROMIUM_PATH'), headless=True, args=['--no-sandbox'])
    page = browser.new_page(viewport={'width':1440,'height':1050}, reduced_motion='reduce')
    page.on('pageerror', lambda e: errors.append(str(e)))
    page.on('request', lambda r: requests.append(r.url))
    page.goto(base + 'index.html#/overview')
    nav = page.locator('#navigation a[href="#/games"]')
    nav.wait_for()
    # The sidebar is intentionally pre-rendered; wait for catalog readiness before timing requests.
    page.locator('#catalog-loading').wait_for(state='detached')
    page.evaluate('window.atlasNavigationSentinel = 42')
    check('single Games tab in original navigation', nav.count() == 1)
    original_heading = page.locator('#page h1').inner_text()
    catalog_requests = len([u for u in requests if '/data/terms-' in u])
    nav.click()
    page.locator('#start-quiz').wait_for()
    check('Games changes only hash, not original document', page.url.endswith('index.html#/games') and page.evaluate('window.atlasNavigationSentinel') == 42)
    check('original shell and sidebar remain', page.locator('.app-shell').count()==1 and page.locator('#sidebar').is_visible())
    check('native content, no iframe or second masthead', page.locator('iframe').count()==0 and page.locator('.masthead').count()==0 and page.locator('main').count()==1)
    check('active tab and breadcrumb agree', nav.get_attribute('aria-current')=='page' and page.locator('#breadcrumb').inner_text()=='Games')
    check('dictionary reused without another download', catalog_requests == len([u for u in requests if '/data/terms-' in u]))
    technique_ids = set(page.evaluate('Array.from(window.AtlasGames.techniqueIds)'))
    check('Techniques selectable in native Games topic', page.locator('#topic option[value="Techniques"]').count()==1)
    page.locator('#topic').select_option('Techniques')
    size = int(page.locator('#pool-count').inner_text().split()[0].replace(',', ''))
    check('Techniques narrows native playable deck', 100 <= size <= len(technique_ids))
    page.locator('#quiz-count').select_option('5')
    page.locator('#start-quiz').click()
    choice_ids = page.locator('[data-answer]').evaluate_all('(els)=>els.map(el=>el.dataset.answer)')
    check('Technique Quiz has only curated choices', len(choice_ids)>=2 and all(i in technique_ids for i in choice_ids))
    exit_round(page)
    page.locator('#start-match').click()
    tile_ids = page.locator('[data-key]').evaluate_all("(els)=>els.map(el=>el.dataset.key.split(':')[0])")
    check('Technique Match has only curated tiles', len(tile_ids)==12 and all(i in technique_ids for i in tile_ids))
    exit_round(page)
    page.locator('#start-flashcards').click()
    term_name = page.locator('#flashcard-front strong').inner_text()
    matching = page.evaluate("async (name)=> (await window.ATLAS_READY).terms.some(r=>r.term===name && window.AtlasGames.techniqueIds.has(r.id))", term_name)
    check('Technique Flashcards have only curated vocabulary', matching)
    exit_round(page)
    page.locator('#reset-filters').click()
    check('Reset clears Techniques topic', page.locator('#topic').input_value()=='')
    # Flashcards: test the visible term, real flip, keyboard navigation, and game exit.
    page.locator('#flashcard-count').select_option('10')
    page.locator('#start-flashcards').click()
    check('flashcards start inside the Games tab', page.locator('#flip-card').is_visible() and page.locator('#flashcard-front').get_attribute('aria-hidden')=='false')
    page.locator('#flip-card').click()
    check('tap-to-flip reveals dictionary definition', page.locator('#flip-card').get_attribute('aria-pressed')=='true' and page.locator('#flashcard-back').get_attribute('aria-hidden')=='false' and page.locator('#flashcard-link').is_visible())
    page.keyboard.press('ArrowRight')
    check('right arrow advances to next term front', page.locator('.flash-panel .eyebrow').inner_text().startswith('CARD 2 / 10') and page.locator('#flip-card').get_attribute('aria-pressed')=='false')
    page.keyboard.press('ArrowLeft')
    check('left arrow moves back to first term', page.locator('.flash-panel .eyebrow').inner_text().startswith('CARD 1 / 10'))
    exit_round(page)
    page.screenshot(path=str(out/'games-native-desktop.png'), full_page=True)
    rows = page.evaluate('async () => (await window.ATLAS_READY).terms')
    by_definition = {r['definition']:r for r in rows}
    page.locator('#query').fill('no-such-concept-zzzz')
    check('empty filtered deck disables both games', page.locator('#start-quiz').is_disabled() and page.locator('#start-match').is_disabled())
    page.locator('#reset-filters').click()
    page.locator('#quiz-count').select_option('5')
    page.locator('#start-quiz').click()
    record = by_definition[page.locator('#question-title').evaluate('(el)=>el.lastChild.textContent')]
    page.locator(f'[data-answer="{record["id"]}"]').click()
    check('quiz feedback works inside original workspace', page.locator('#feedback h3').inner_text().startswith('Correct.'))
    page.locator('#feedback [data-game-concept]').click()
    check('concept opens original Atlas dialog, not another site', page.locator('#record-dialog').is_visible() and page.locator('#record-title').inner_text()==record['term'] and page.url.endswith('#/games'))
    page.locator('[data-action=close-record]').click()
    check('closing concept returns to same question', page.locator('#feedback').is_visible() and '1 correct' in page.locator('#quiz-score').inner_text())
    for i in range(4):
        page.locator('[data-action=next]').click()
        page.locator('[data-action=skip]').click()
    page.locator('[data-action=next]').click()
    check('results and missed review remain in tab', '1 / 5' in page.locator('.result-score').inner_text() and page.locator('.review-item').count()==4)
    page.locator('[data-action=retry-missed]').click()
    check('missed concepts retry with full choice pool', page.locator('[data-answer]').count()==4)
    exit_round(page)
    page.locator('#answer-mode').select_option('typed')
    page.locator('#start-quiz').click()
    record = by_definition[page.locator('#question-title').evaluate('(el)=>el.lastChild.textContent')]
    page.locator('#typed-answer').fill(record['term'].upper())
    page.locator('#typed-answer').press('Enter')
    check('typed recall works in integrated view', page.locator('#feedback h3').inner_text().startswith('Correct.'))
    exit_round(page)
    page.locator('#start-match').click()
    check('Match starts inside same shell', page.locator('.tile').count()==12 and page.locator('#sidebar').is_visible())
    keys = page.locator('.tile').evaluate_all('(els)=>els.map(e=>e.dataset.key)')
    first = keys[0]
    wrong = next(k for k in keys if k.split(':')[0]!=first.split(':')[0])
    page.locator(f'[data-key="{first}"]').click()
    page.locator(f'[data-key="{wrong}"]').click()
    check('incorrect match penalty displayed', '+1 second' in page.locator('#match-status').inner_text())
    page.locator('#navigation a[href="#/overview"]').click()
    page.wait_for_timeout(600)
    check('leaving running game restores original overview', page.locator('#page h1').inner_text()==original_heading and not page.locator('.atlas-games').count())
    check('game styles do not mark whole page playing', 'is-playing' not in (page.locator('body').get_attribute('class') or ''))
    for _ in range(3):
        page.locator('#navigation a[href="#/games"]').click()
        page.locator('#start-match').click()
        page.locator('#navigation a[href="#/dictionary"]').click()
    page.locator('#navigation a[href="#/games"]').click()
    page.locator('#start-match').click()
    keys = page.locator('.tile').evaluate_all('(els)=>els.map(e=>e.dataset.key)')
    for id in dict.fromkeys(k.split(':')[0] for k in keys):
        page.locator(f'[data-key="{id}:term"]').click()
        page.locator(f'[data-key="{id}:definition"]').click()
    check('matching completes after repeated route changes', page.locator('#round-title').inner_text()=='Board cleared' and page.locator('.review-item').count()==6)
    exit_round(page)
    page.locator('#theme-toggle').click()
    theme = page.locator('html').get_attribute('data-theme')
    check('original global theme toggle applies to Games', theme in ('light','dark'))
    page.locator('#navigation a[href="#/overview"]').click()
    page.locator('#navigation a[href="#/games"]').click()
    check('Games never resets global theme', page.locator('html').get_attribute('data-theme')==theme)
    page.set_viewport_size({'width':390,'height':844})
    check('mobile Games has no horizontal overflow', page.evaluate('document.documentElement.scrollWidth<=innerWidth'))
    page.locator('#start-match').click()
    page.screenshot(path=str(out/'games-native-mobile.png'),full_page=True)
    check('mobile matching fits original workspace', page.evaluate('document.documentElement.scrollWidth<=innerWidth'))
    check('mobile definitions untruncated', page.locator('.tile').evaluate_all('(els)=>els.every(e=>e.scrollHeight<=e.clientHeight+1)'))
    page.locator('#discover-mobile-nav > summary').click()
    page.locator('#discover-mobile-nav .site-mobile-chrome__menu > a:not(.site-mobile-chrome__brand)[href="#/overview"]').click()
    page.wait_for_function("location.hash === '#/overview' && !document.getElementById('discover-mobile-nav').open && !document.querySelector('.atlas-games')")
    check('mobile drawer exits game and closes', page.locator('#discover-mobile-nav').evaluate('el => !el.open') and page.url.endswith('#/overview'))
    page.go_back()
    page.locator('#start-quiz').wait_for()
    check('browser Back restores Games route', page.url.endswith('#/games'))
    page.reload()
    page.locator('#start-quiz').wait_for()
    check('direct reload supports Games deep link', page.url.endswith('#/games'))
    offline=browser.new_page(viewport={'width':1440,'height':1000})
    offline.on('pageerror',lambda e:errors.append(str(e)))
    offline.route('**/*', lambda route: route.continue_() if '/downloads/Atlas_Demo_Offline.html' in route.request.url else route.abort())
    offline.goto(base+'downloads/Atlas_Demo_Offline.html#/games')
    offline.locator('#start-quiz').wait_for()
    offline.locator('#start-quiz').click()
    check('offline quiz works without network assets', offline.locator('#question-title').is_visible())
    exit_round(offline)
    offline.locator('#start-match').click()
    check('offline matching works without network assets', offline.locator('.tile').count()==12)
    exit_round(offline)
    offline.locator('#start-flashcards').click()
    offline.locator('#flip-card').click()
    check('offline flashcards flip without network assets', offline.locator('#flashcard-back').get_attribute('aria-hidden')=='false')

    check('no runtime errors in either interface', not errors)
    browser.close()
report={'checks_passed':len(checks),'checks':checks,'errors':errors,'base':base,'scope':'Real Atlas page and production catalog loader; offline export blocks other requests.'}
(out/'report.json').write_text(json.dumps(report,indent=2))
print(json.dumps(report,indent=2))
